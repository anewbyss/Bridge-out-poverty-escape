'use strict';

// Builds the phone (iOS Home Screen) app into ./site:
//   - the same pages as the server version, with paths made relative so it
//     works from a GitHub Pages sub-folder
//   - engine.js: the server's own modules bundled for the browser, with
//     mobile/shims.js standing in for Node built-ins
//   - sql.js (SQLite compiled to WebAssembly), a service worker for offline
//     use, and an app manifest
// Usage: node scripts/build-mobile.js [outDir]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'site'));
const PAGES = ['index.html', 'followup.html', 'directory.html', 'staff.html'];

const MODULES = [
  'server/taxonomy', 'server/matcher', 'server/validate', 'server/db', 'server/store',
  'server/live', 'server/discovery', 'server/app', 'mobile/auth', 'mobile/shims',
];
const BUILTINS = {
  fs: 'fs', 'node:fs': 'fs', path: 'path', 'node:path': 'path', crypto: 'crypto', 'node:crypto': 'crypto',
  'node:sqlite': 'sqlite', readline: 'readline', 'node:readline': 'readline', stream: 'stream', 'node:stream': 'stream',
};
const SUBSTITUTE = { '/server/auth': '/mobile/auth' };

function bundle() {
  const parts = MODULES.map((m) => {
    const src = fs.readFileSync(path.join(ROOT, `${m}.js`), 'utf8');
    return `${JSON.stringify(`/${m}`)}: function (module, exports, require, __dirname, Buffer) {\n${src}\n}`;
  });
  return `'use strict';
// Generated by scripts/build-mobile.js — do not edit.
var BOP_ENGINE = (function () {
  var defs = {\n${parts.join(',\n')}\n};
  var builtins = ${JSON.stringify(BUILTINS)};
  var substitute = ${JSON.stringify(SUBSTITUTE)};
  var cache = {};
  function resolve(from, req) {
    if (builtins[req]) return { builtin: builtins[req] };
    var dir = from.replace(/\\/[^/]*$/, '');
    var parts = (dir + '/' + req).split('/');
    var out = [];
    for (var i = 0; i < parts.length; i++) {
      if (parts[i] === '..') out.pop();
      else if (parts[i] && parts[i] !== '.') out.push(parts[i]);
    }
    var id = '/' + out.join('/').replace(/\\.js$/, '');
    return { id: substitute[id] || id };
  }
  function load(id) {
    if (cache[id]) return cache[id].exports;
    if (!defs[id]) throw new Error('Module not bundled: ' + id);
    var module = (cache[id] = { exports: {} });
    var shims = id === '/mobile/shims' ? null : load('/mobile/shims');
    defs[id](module, module.exports, function (req) {
      var r = resolve(id, req);
      return r.builtin ? load('/mobile/shims')[r.builtin] : load(r.id);
    }, id.replace(/\\/[^/]*$/, ''), shims ? shims.Buffer : undefined);
    return module.exports;
  }
  return { require: load };
})();
`;
}

// Root-absolute paths → relative, so the app works from any folder.
const REWRITES = [
  [/href="\/"/g, 'href="index.html"'],
  [/href: '\/'/g, "href: 'index.html'"],
  [/(["'`])\/\?staff=1/g, '$1index.html?staff=1'],
  [/(["'`])\/(styles\.css|common\.js|intake\.js|followup\.js|directory\.js|staff\.js)/g, '$1$2'],
  [/(["'`])\/(followup|directory|staff)(?=["'`?])/g, '$1$2.html'],
];

const HEAD = `  <meta name="theme-color" content="#1d6b5f">
  <meta name="apple-mobile-web-app-capable" content="yes">
  <meta name="mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-status-bar-style" content="default">
  <meta name="apple-mobile-web-app-title" content="Bridge">
  <link rel="manifest" href="manifest.webmanifest">
  <link rel="apple-touch-icon" href="icons/icon-180.png">
  <link rel="icon" href="icons/icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="mobile.css">
  <script src="vendor/sql-wasm.js" defer></script>
  <script src="engine.js" defer></script>
  <script src="shell.js" defer></script>
`;

function rewrite(text) {
  for (const [re, to] of REWRITES) text = text.replace(re, to);
  return text;
}

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function build() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  for (const f of fs.readdirSync(path.join(ROOT, 'public'))) {
    let text = fs.readFileSync(path.join(ROOT, 'public', f), 'utf8');
    if (f.endsWith('.html')) {
      text = rewrite(text)
        .replace('<link rel="stylesheet" href="styles.css">', (m) => `${m}\n${HEAD}`)
        .replace('viewport" content="width=device-width, initial-scale=1"', 'viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"')
        // Staff entry on the youth-facing pages (the phone belongs to staff).
        .replace(/(<a href="directory\.html"[^>]*>All resources<\/a>)/, '$1\n      <a href="staff.html">Staff</a>');
    } else if (f.endsWith('.js')) text = rewrite(text);
    fs.writeFileSync(path.join(OUT, f), text);
  }

  fs.writeFileSync(path.join(OUT, 'engine.js'), bundle());
  for (const f of ['shell.js', 'sw.js', 'mobile.css', 'manifest.webmanifest']) copy(path.join(ROOT, 'mobile', f), path.join(OUT, f));
  for (const f of fs.readdirSync(path.join(ROOT, 'mobile', 'icons'))) copy(path.join(ROOT, 'mobile', 'icons', f), path.join(OUT, 'icons', f));
  const sqljs = path.dirname(require.resolve('sql.js/dist/sql-wasm.js'));
  for (const f of ['sql-wasm.js', 'sql-wasm.wasm']) copy(path.join(sqljs, f), path.join(OUT, 'vendor', f));
  copy(path.join(ROOT, 'data', 'resources.seed.json'), path.join(OUT, 'data', 'resources.seed.json'));
  // Weekly public-data files, if scripts/publish-data.js produced them.
  for (const f of ['directory.json', 'leads.json']) {
    const p = path.join(ROOT, 'build', f);
    if (fs.existsSync(p)) copy(p, path.join(OUT, 'data', f));
  }

  // Stamp the service worker so each build refreshes the offline cache.
  const files = [];
  (function walk(dir) {
    for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else files.push(path.relative(OUT, p).split(path.sep).join('/'));
    }
  })(OUT);
  const shell = files.filter((f) => !f.startsWith('data/') && f !== 'sw.js');
  const sw = fs.readFileSync(path.join(OUT, 'sw.js'), 'utf8')
    .replace('__VERSION__', String(Date.now()))
    .replace("'__FILES__'", JSON.stringify(['./', ...shell, 'data/resources.seed.json']));
  fs.writeFileSync(path.join(OUT, 'sw.js'), sw);

  // Guard: no root-absolute links may survive (they break under /repo-name/).
  const bad = [];
  for (const f of files.filter((x) => /\.(html|js)$/.test(x) && !x.startsWith('vendor/') && x !== 'engine.js')) {
    const text = fs.readFileSync(path.join(OUT, f), 'utf8');
    const m = text.match(/(?:href|src)\s*[=:]\s*["'`]\/(?!api\/)[^"'`]*/g);
    if (m) bad.push(`${f}: ${m.join(', ')}`);
  }
  if (bad.length) throw new Error(`Root-absolute paths left in build:\n${bad.join('\n')}`);
  console.log(`Built phone app into ${path.relative(process.cwd(), OUT) || '.'} (${files.length} files)`);
}

build();
